/**
 * يبحث عن إحداثيات محافظة بالاسم، مع تطبيع بسيط (إزالة المسافات و"محافظة").
 * يرجع null لو الاسم مش معروف بدل ما يرمي استثناء — الاستدعاء المسؤول
 * يقرر هل يتجاهل النقطة أو يجمعها ضمن "غير محدد".
 */
export function getGovernorateCoord(rawName: string | null | undefined): GovernorateCoord | null {
  if (!rawName) return null;
  const cleaned = rawName.trim().replace(/^محافظة\s*/, "").trim();
  if (RAW_COORDS[cleaned]) return RAW_COORDS[cleaned];

  // محاولة مطابقة جزئية (لو الاسم المخزّن فيه كلمة زيادة، مثلاً "القاهرة الجديدة")
  const match = Object.keys(RAW_COORDS).find((key) => cleaned.includes(key) || key.includes(cleaned));
  return match ? RAW_COORDS[match] : null;
}
